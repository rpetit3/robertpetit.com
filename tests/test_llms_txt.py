"""Guard static/llms.txt links against renamed or removed pages.

The SPA catch-all in netlify.toml answers a dead path with the homepage and
status 200, so a stale llms.txt link is invisible in production.
"""

import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).parents[1]
LLMS = ROOT / "static" / "llms.txt"
BASE = "https://www.robertpetit.com"


def urls() -> list[str]:
    return re.findall(r"\]\((https://www\.robertpetit\.com/[^)]*)\)", LLMS.read_text())


def resolves(path: str) -> bool:
    route = path.strip("/")
    if route in {"sitemap.xml", "index.xml"}:
        return True  # generated by Hugo at build time
    if Path(route).suffix in {".pdf", ".xml"}:
        return (ROOT / "static" / route).exists()
    return any(
        candidate.exists()
        for candidate in (
            ROOT / "content" / f"{route}.md",
            ROOT / "content" / route / "_index.md",
            ROOT / "content" / route,
        )
    )


def test_llms_txt_targets_exist():
    for url in urls():
        path = urlparse(url).path
        assert resolves(path), f"{url} matches no content page"


def test_llms_txt_uses_canonical_host():
    for url in urls():
        assert url.startswith(BASE + "/"), f"{url} is not on the canonical host"


def test_robots_txt_points_at_the_sitemap():
    robots = (ROOT / "static" / "robots.txt").read_text()
    assert f"Sitemap: {BASE}/sitemap.xml" in robots